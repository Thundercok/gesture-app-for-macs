#!/usr/bin/env python3
"""Commit-policy experiment: WHEN to fire a gesture (latency vs false triggers). NumPy only.

  python3 commit_policy_rl.py                       # both experiments (~4 min)
  python3 commit_policy_rl.py --only table          # learned policies vs tuned rule
  python3 commit_policy_rl.py --only personalise    # per-user adaptation: bandit vs offline replay tuning
  python3 commit_policy_rl.py --only curve          # data budget: rule vs learned policies, 500 .. 24000 episodes (~3 min)

Framing: early classification of a streaming signal (RL halting policy: EARLIEST, KDD'19). Per frame the policy sees a
Markov summary of the history and picks WAIT or COMMIT.
  reward  TP: 1 - lam*t/H | FP: -C_fp | intent never committed: -C_miss | nuisance never committed: 0
Structural fact used below: observations do NOT depend on the action (the hand moves regardless), so any candidate policy
can be replayed on recorded episodes. That gives full-information (counterfactual) feedback, which a bandit never has.

EXPERIMENT 1 (table): each method re-tuned per C_fp, 20k held-out test episodes
  rule      consecutive-frame gate (aperture / palm-facing / face-clearance thresholds, random-search tuned on validation)
  clf+thr   supervised MLP P(intent | state) + validation-tuned confidence threshold (standard early-classification baseline)
  fqi       offline value-based RL: fitted Q-iteration on the recorded episodes + validation-tuned commit margin
  pg        REINFORCE with learned baseline, from scratch (untuned)
EXPERIMENT 2 (personalise): a user whose deliberate pinch is shallower than the population's
  bandit      Thompson sampling over rule configurations, feedback only for the arm played (what online RL gets)
  full-info   evaluate every configuration on the same recorded episodes (what replay gets)
  local/global arms: neighbours of the population rule (trust region) vs 59 random configurations

All data is generated by `simulate()`, which I wrote. Treat the numbers as a check on methods and costs, not as a
statement about your users. Replace `simulate()` with recorded episodes to get the real answer.
"""
import argparse, math
import numpy as np

H, FPS, NF = 40, 60.0, 9                       # horizon (frames), camera rate, state features
LAM, C_MISS = 0.6, 1.0


# ------------------------------------------------------------------ simulator (edit me / replace with real episodes)
def _dips(rng, n, base, kmax, dmax, depth_hi):
    """Transient aperture dips (accidental pinch-like closures) added to `base` [n,H]."""
    t = np.arange(H)[None, None, :]
    k = rng.integers(0, kmax + 1, n)[:, None]
    s = rng.uniform(3, H - 8, (n, kmax))[:, :, None]
    d = rng.uniform(2, dmax, (n, kmax))[:, :, None]
    m = rng.uniform(0.10, depth_hi, (n, kmax))[:, :, None]
    on = (np.arange(kmax)[None, :] < k)[:, :, None]
    u = np.clip((t - s) / d, 0, 1)                                        # 0..1 across the dip
    dip = np.where(on & (t >= s) & (t < s + d), base[:, None, :] - (base[:, None, :] - m) * np.sin(np.pi * u), base[:, None, :])
    return np.minimum(base, dip.min(axis=1))


def _closure(rng, n, m_lo=0.10, m_hi=0.35, shift=0.0):
    """Deliberate pinch: closes over 5-16 frames from onset 4-14, then holds."""
    t = np.arange(H)[None, :]
    t0 = rng.uniform(4, 14, (n, 1)); tau = rng.uniform(5, 16, (n, 1)); m = rng.uniform(m_lo, m_hi, (n, 1)) + shift
    u = np.clip((t - t0) / tau, 0, 1)
    return 0.9 - (0.9 - m) * 0.5 * (1 - np.cos(np.pi * u)), (t0 + tau)[:, 0]


def simulate(n, rng, shift=0.0):
    """-> obs [n,H,3] (aperture, palm-facing, face-clearance), y [n] (1 = intended), close_t [n] (frame closure completes)."""
    kind = rng.choice(4, n, p=[0.35, 0.25, 0.25, 0.15])                   # 0 intent, 1 talk, 2 chin, 3 rest
    ap = np.full((n, H), 0.9); close_t = np.full(n, np.nan)
    pb = np.empty(n); cb = np.empty(n)
    i = kind == 0
    ap[i], close_t[i] = _closure(rng, i.sum(), shift=shift); pb[i] = rng.uniform(0.45, 0.9, i.sum()); cb[i] = rng.uniform(0.5, 0.95, i.sum())
    i = kind == 1                                                          # talking with hands: many transient dips
    ap[i] = _dips(rng, i.sum(), ap[i], 3, 14, 0.45); pb[i] = rng.uniform(0.35, 0.85, i.sum()); cb[i] = rng.uniform(0.5, 0.95, i.sum())
    i = kind == 2                                                          # chin / cheek: near the face, sometimes a held closure
    held = rng.random(i.sum()) < 0.35
    a2 = _dips(rng, i.sum(), ap[i], 2, 14, 0.45)
    a2[held] = _closure(rng, held.sum())[0]
    ap[i] = a2; pb[i] = rng.uniform(0.25, 0.75, i.sum()); cb[i] = rng.uniform(0.10, 0.60, i.sum())
    i = kind == 3                                                          # hand resting in view
    pb[i] = rng.uniform(0.5, 0.9, i.sum()); cb[i] = rng.uniform(0.5, 0.95, i.sum())
    obs = np.stack([ap + rng.normal(0, 0.08, (n, H)),
                    pb[:, None] + rng.normal(0, 0.10, (n, H)),
                    cb[:, None] + rng.normal(0, 0.10, (n, H))], axis=2)
    return np.clip(obs, 0, 1), (kind == 0).astype(int), close_t


def features(obs):
    """Markov summary of the history, [n,H,NF]. Uses only frames <= t."""
    n = len(obs); a, p, c = obs[..., 0], obs[..., 1], obs[..., 2]
    a_s, p_e, c_e = a.copy(), p.copy(), c.copy()
    run = np.zeros((n, H)); r = np.zeros(n)
    for t in range(H):
        if t:
            a_s[:, t] = 0.5 * a[:, t] + 0.5 * a_s[:, t - 1]
            p_e[:, t] = 0.25 * p[:, t] + 0.75 * p_e[:, t - 1]
            c_e[:, t] = 0.25 * c[:, t] + 0.75 * c_e[:, t - 1]
        r = np.where(a_s[:, t] < 0.3, np.minimum(r + 1, 20), 0); run[:, t] = r
    da = a_s - np.concatenate([np.repeat(a_s[:, :1], 3, 1), a_s[:, :-3]], 1)
    cnt = np.arange(1, H + 1)[None, :]
    return np.stack([a_s, np.minimum.accumulate(a_s, 1), run / 20, p_e, c_e,
                     np.cumsum(p, 1) / cnt, np.cumsum(c, 1) / cnt, da, np.broadcast_to(cnt / H, (n, H))], axis=2)


# ------------------------------------------------------------------ scoring
def score(T, y, cfp):
    """T = commit frame (H = never). Returns dict of reward, TPR, FPR, latency ms."""
    com = T < H; tp = com & (y == 1); fp = com & (y == 0); fn = ~com & (y == 1)
    rew = np.where(tp, 1 - LAM * T / H, 0.0) - cfp * fp - C_MISS * fn
    return dict(reward=rew.mean(), tpr=tp.sum() / max(1, (y == 1).sum()), fpr=fp.sum() / max(1, (y == 0).sum()),
                lat=(T[tp].mean() / FPS * 1000) if tp.any() else float("nan"))


def first_true(mask):
    return np.where(mask.any(1), mask.argmax(1), H)


# ------------------------------------------------------------------ baselines
def rule_T(S, th):
    tc, tp_, ta, k = th
    run = np.zeros(len(S)); ok = np.zeros(S.shape[:2], bool)
    for t in range(H):
        run = np.where(S[:, t, 0] < ta, run + 1, 0)
        ok[:, t] = (run >= k) & (S[:, t, 3] > tp_) & (S[:, t, 4] > tc)
    return first_true(ok)


def tune_rule(S, y, cfp, rng, trials=400):
    best = (-1e9, None)
    for _ in range(trials):
        th = (rng.uniform(0.1, 0.7), rng.uniform(0.1, 0.7), rng.uniform(0.15, 0.6), rng.integers(1, 14))
        r = score(rule_T(S, th), y, cfp)["reward"]
        if r > best[0]:
            best = (r, th)
    return best[1]


class MLP:
    def __init__(self, nin, nh, nout, rng):
        self.W1 = rng.normal(0, 1 / math.sqrt(nin), (nin, nh)); self.b1 = np.zeros(nh)
        self.W2 = rng.normal(0, 0.1 / math.sqrt(nh), (nh, nout)); self.b2 = np.zeros(nout)
        self.m = [np.zeros_like(p) for p in self.P()]; self.v = [np.zeros_like(p) for p in self.P()]; self.k = 0

    def P(self): return [self.W1, self.b1, self.W2, self.b2]

    def forward(self, x):
        self.x = x; self.h = np.tanh(x @ self.W1 + self.b1)
        return self.h @ self.W2 + self.b2

    def grads(self, dout):
        dh = (dout @ self.W2.T) * (1 - self.h ** 2)
        return [self.x.T @ dh, dh.sum(0), self.h.T @ dout, dout.sum(0)]

    def adam(self, g, lr):
        self.k += 1
        for p, gi, m, v in zip(self.P(), g, self.m, self.v):
            m *= 0.9; m += 0.1 * gi; v *= 0.999; v += 0.001 * gi * gi
            p -= lr * (m / (1 - 0.9 ** self.k)) / (np.sqrt(v / (1 - 0.999 ** self.k)) + 1e-8)


def train_classifier(S, y, rng, epochs=25):
    X = S.reshape(-1, NF); Y = np.repeat(y, H).astype(float); net = MLP(NF, 48, 1, rng)
    for _ in range(epochs):
        perm = rng.permutation(len(X))
        for i in range(0, len(X), 4096):
            b = perm[i:i + 4096]; p = 1 / (1 + np.exp(-net.forward(X[b])[:, 0]))
            net.adam(net.grads(((p - Y[b]) / len(b))[:, None]), 3e-3)
    return lambda S_: 1 / (1 + np.exp(-net.forward(S_.reshape(-1, NF))[:, 0])).reshape(len(S_), H)


def clf_T(prob, psi):
    return first_true(prob >= psi)


def tune_clf(prob, y, cfp):
    best = (-1e9, 0.5)
    for psi in np.linspace(0.3, 0.995, 80):
        r = score(clf_T(prob, psi), y, cfp)["reward"]
        best = max(best, (r, psi))
    return best[1]


# ------------------------------------------------------------------ RL: REINFORCE + learned baseline
def softmax(z):
    e = np.exp(z - z.max(1, keepdims=True)); return e / e.sum(1, keepdims=True)


def train_pg(S, y, cfp, rng, iters=400, B=1024, lr=3e-3, ent=0.02):
    net = MLP(NF, 48, 3, rng)                                               # [logit wait, logit commit, value]
    net.b2[1] = -4.0                                                        # start at ~2% commit/frame, else it collapses to 'commit at t=0'
    for _ in range(iters):
        idx = rng.integers(0, len(S), B); Sb, yb = S[idx], y[idx]
        alive = np.ones(B, bool); T = np.full(B, H); rows = []
        for t in range(H):
            ai = np.where(alive)[0]
            if not len(ai): break
            pi = softmax(net.forward(Sb[ai, t])[:, :2])
            a = (rng.random(len(ai)) < pi[:, 1]).astype(int)
            rows.append((ai, t, a))
            done = ai[a == 1]; T[done] = t; alive[done] = False
        com = T < H
        R = np.where(com & (yb == 1), 1 - LAM * T / H, 0.0) - cfp * (com & (yb == 0)) - C_MISS * (~com & (yb == 1))
        X = np.concatenate([Sb[ai, t] for ai, t, _ in rows]); A_ = np.concatenate([a for _, _, a in rows])
        Rr = np.concatenate([R[ai] for ai, _, _ in rows])
        out = net.forward(X); pi = softmax(out[:, :2]); V = out[:, 2]
        Rr = Rr / max(1.0, cfp); adv = Rr - V
        onehot = np.eye(2)[A_]
        Hs = -(pi * np.log(pi + 1e-12)).sum(1, keepdims=True)
        d = np.zeros_like(out)
        d[:, :2] = -adv[:, None] * (onehot - pi) + ent * pi * (np.log(pi + 1e-12) + Hs)
        d[:, 2] = V - Rr
        net.adam(net.grads(d / len(X)), lr)

    def greedy_T(S_):
        out = net.forward(S_.reshape(-1, NF))[:, :2].reshape(len(S_), H, 2)
        return first_true(out[..., 1] > out[..., 0])
    return greedy_T


# ------------------------------------------------------------------ RL, value-based: fitted Q-iteration on logged episodes
def train_fqi(S, y, cfp, rng, sweeps=40, epochs=2, lr=2e-3):
    """Optimal stopping via Bellman backups on recorded episodes. Observations do not depend on the action, so
    Q_commit(s_t) regresses onto the known terminal reward, and V_wait(s_t) onto max(Q_commit, V_wait)(s_{t+1})."""
    n = len(S); sc = max(1.0, cfp)                                          # reward scale, keeps targets O(1)
    t = np.arange(H)[None, :]
    r_c = np.where(y[:, None] == 1, 1 - LAM * t / H, -cfp) / sc             # reward if we commit at t
    r_end = np.where(y == 1, -C_MISS, 0.0) / sc                             # reward if we never commit
    X = S.reshape(-1, NF); Tc = r_c.reshape(-1)
    net = MLP(NF, 64, 2, rng)                                               # [Q_commit, V_wait]
    for _ in range(sweeps):
        out = net.forward(X); vstar = np.maximum(out[:, 0], out[:, 1]).reshape(n, H)
        tw = np.empty((n, H)); tw[:, :-1] = vstar[:, 1:]; tw[:, -1] = r_end
        Y = np.stack([Tc, tw.reshape(-1)], 1)
        for _ in range(epochs):
            perm = rng.permutation(len(X))
            for i in range(0, len(X), 4096):
                b = perm[i:i + 4096]
                net.adam(net.grads((net.forward(X[b]) - Y[b]) / len(b)), lr)

    def margin(S_):
        out = net.forward(S_.reshape(-1, NF)).reshape(len(S_), H, 2)
        return out[..., 0] - out[..., 1]
    return margin


# ------------------------------------------------------------------ personalisation: bandit over rule configurations
def rule_rewards(S, y, cfgs, cfp):
    """Reward of every candidate config on every episode -> [n, K] (what a bandit would observe for the arm it played)."""
    out = np.empty((len(S), len(cfgs)))
    for k, th in enumerate(cfgs):
        T = rule_T(S, th); com = T < H
        out[:, k] = np.where(com & (y == 1), 1 - LAM * T / H, 0.0) - cfp * (com & (y == 0)) - C_MISS * (~com & (y == 1))
    return out


def thompson(R, rng, prior_sd=1.0):
    """Gaussian Thompson sampling, one episode at a time, bandit feedback only. Returns per-round arm and reward."""
    n, K = R.shape; cnt = np.zeros(K); tot = np.zeros(K); sq = np.zeros(K); arms = np.empty(n, int); got = np.empty(n)
    for i in range(n):
        sd = math.sqrt(max(1e-3, (sq.sum() / max(1, cnt.sum())) - (tot.sum() / max(1, cnt.sum())) ** 2))   # pooled reward sd
        draw = rng.normal(tot / (cnt + 1), (sd + prior_sd * (cnt == 0)) / np.sqrt(cnt + 1))
        k = int(draw.argmax()); r = R[i, k]
        cnt[k] += 1; tot[k] += r; sq[k] += r * r; arms[i] = k; got[i] = r
    return arms, got, tot / np.maximum(cnt, 1), cnt


def personalise(cfp, seed, shift=0.12, sizes=(50, 200, 800), local=False):
    rng = np.random.default_rng(100 + seed)
    o, y, _ = simulate(6000, rng); S = features(o)
    th_pop = tune_rule(S, y, cfp, rng)
    if local:                                                                            # trust region: only neighbours of the population rule
        cand = [th_pop] + [(th_pop[0] + rng.normal(0, .06), th_pop[1] + rng.normal(0, .06), th_pop[2] + rng.normal(0, .06),
                            int(np.clip(round(th_pop[3] + rng.normal(0, 1.5)), 1, 14))) for _ in range(59)]
    else:                                                                                # global: 59 random configs
        cand = [th_pop] + [(rng.uniform(0.1, 0.7), rng.uniform(0.1, 0.7), rng.uniform(0.15, 0.6), int(rng.integers(1, 14))) for _ in range(59)]
    ou, yu, _ = simulate(max(sizes), rng, shift); Su = features(ou)                     # this user's adaptation stream
    ot, yt, _ = simulate(20000, np.random.default_rng(20_000 + seed), shift); St = features(ot)
    Rt = rule_rewards(St, yt, cand, cfp).mean(0); Ru = rule_rewards(Su, yu, cand, cfp)
    out = {"population rule": Rt[0], "best of 60 (oracle)": Rt.max()}
    for n in sizes:
        arms, got, mean_k, cnt = thompson(Ru[:n], rng)
        out[f"bandit after {n}"] = (Rt[int(np.argmax(np.where(cnt > 0, mean_k, -1e9)))], got.mean(), Ru[:n, 0].mean())  # test, explore-phase, pop-rule on same eps
        out[f"full-info after {n}"] = Rt[int(Ru[:n].mean(0).argmax())]
    return out


# ------------------------------------------------------------------ experiment
def run(cfp, seed, iters, ntrain=8000, nval=6000, ntest=20000):
    rng = np.random.default_rng(seed)
    o, y, _ = simulate(ntrain, rng); S = features(o)
    ov, yv, _ = simulate(nval, rng); Sv = features(ov)                      # validation: tunes rule / threshold
    ot, yt, ct = simulate(ntest, np.random.default_rng(10_000 + seed)); St = features(ot)
    res = {}
    res["rule"] = score(rule_T(St, tune_rule(Sv, yv, cfp, rng)), yt, cfp)
    prob = train_classifier(S, y, rng)
    res["clf+thr"] = score(clf_T(prob(St), tune_clf(prob(Sv), yv, cfp)), yt, cfp)
    marg = train_fqi(S, y, cfp, rng); mv = marg(Sv)
    delta = max((score(first_true(mv >= d), yv, cfp)["reward"], d) for d in np.linspace(-0.05, 0.6, 66))[1]
    res["fqi"] = score(first_true(marg(St) >= delta), yt, cfp)
    res["pg"] = score(train_pg(S, y, cfp, rng, iters)(St), yt, cfp)
    floor = np.nanmean(ct[yt == 1]) / FPS * 1000                             # closure-complete time: hard latency floor
    return res, floor


def report_table(cfps, seeds, iters):
    print(f"H={H} frames @ {FPS:.0f} fps, lam={LAM}, C_miss={C_MISS}; mean over {seeds} seed(s), 20k test episodes each")
    for cfp in cfps:
        runs = [run(cfp, s, iters) for s in range(seeds)]
        print(f"\nC_fp = {cfp:g}   (latency floor: closure completes at {np.mean([r[1] for r in runs]):.0f} ms)")
        print(f"{'method':<9}{'reward':>14}{'TPR %':>9}{'FPR %':>9}{'latency ms':>12}")
        for m in ("rule", "clf+thr", "fqi", "pg"):
            g = lambda k: np.array([r[0][m][k] for r in runs])
            lat = g("lat")[~np.isnan(g("lat"))]                              # nan = never committed correctly
            print(f"{m:<9}{g('reward').mean():>8.3f}+-{g('reward').std():.3f}{100 * g('tpr').mean():>8.1f}"
                  f"{100 * g('fpr').mean():>9.2f}{(f'{lat.mean():.0f}' if len(lat) else 'n/a'):>12}")


def report_personalise(cfp, seeds, shifts=(0.12, 0.2)):
    for shift in shifts:
        print(f"\nPERSONALISE  C_fp={cfp:g}, user's pinch minimum aperture shifted +{shift}, mean over {seeds} users; entries = mean reward")
        for local in (True, False):
            rs = [personalise(cfp, s, shift=shift, local=local) for s in range(seeds)]
            print(f"  arms = {'neighbours of population rule' if local else '59 random configs':<30}"
                  f"population rule {np.mean([r['population rule'] for r in rs]):.3f} | best arm (oracle) {np.mean([r['best of 60 (oracle)'] for r in rs]):.3f}")
            for n in (50, 200, 800):
                b = [r[f"bandit after {n}"] for r in rs]
                print(f"    after {n:>3} episodes: bandit {np.mean([x[0] for x in b]):.3f} (reward while exploring {np.mean([x[1] for x in b]):.3f},"
                      f" population rule on the same episodes {np.mean([x[2] for x in b]):.3f}) | full-info replay {np.mean([r[f'full-info after {n}'] for r in rs]):.3f}")


def report_curve(cfp=10, sizes=(500, 2000, 8000, 24000), seed=0):
    print(f"\nDATA BUDGET  C_fp={cfp:g}: total recorded episodes n (learned methods: 60% fit / 40% tune their threshold; rule tunes on all n). "
          f"Entries = test reward, 20k episodes")
    ot, yt, _ = simulate(20000, np.random.default_rng(30_000 + seed)); St = features(ot)
    print(f"{'n':>7}{'rule':>9}{'clf+thr':>10}{'fqi':>9}")
    for n in sizes:
        rng = np.random.default_rng(300 + seed); o, y, _ = simulate(n, rng); S = features(o); k = int(0.6 * n)
        r_rule = score(rule_T(St, tune_rule(S, y, cfp, rng)), yt, cfp)["reward"]
        prob = train_classifier(S[:k], y[:k], rng)
        r_clf = score(clf_T(prob(St), tune_clf(prob(S[k:]), y[k:], cfp)), yt, cfp)["reward"]
        marg = train_fqi(S[:k], y[:k], cfp, rng); mv = marg(S[k:])
        delta = max((score(first_true(mv >= d), y[k:], cfp)["reward"], d) for d in np.linspace(-0.05, 0.6, 66))[1]
        r_fqi = score(first_true(marg(St) >= delta), yt, cfp)["reward"]
        print(f"{n:>7}{r_rule:>9.3f}{r_clf:>10.3f}{r_fqi:>9.3f}", flush=True)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", choices=["table", "personalise", "curve"])
    ap.add_argument("--cfp", type=float, nargs="+", default=[3, 10, 30])
    ap.add_argument("--iters", type=int, default=400)
    ap.add_argument("--seeds", type=int, default=1)
    a = ap.parse_args()
    if a.only in (None, "table"):
        report_table(a.cfp, a.seeds, a.iters)
    if a.only in (None, "personalise"):
        report_personalise(10, 4)
    if a.only in (None, "curve"):
        report_curve()


if __name__ == "__main__":
    main()
